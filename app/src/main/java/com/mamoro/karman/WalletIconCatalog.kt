    private val cache = ConcurrentHashMap<String, ImageVector>()

    fun vector(key: String): ImageVector = cache.getOrPut(key) {
        val canonical = oldKeys[key] ?: key
        // Material icons live in separate generated *Kt classes in the extended icon artifact.
        // Resolve only the visible grid rows, cache the result, and fall back safely for old data.
        runCatching {
            val iconClass = Class.forName("androidx.compose.material.icons.filled.${canonical}Kt")
            val getter = iconClass.getMethod("get$canonical", Icons.Filled::class.java)
            getter.invoke(null, Icons.Filled) as ImageVector
        }.getOrElse { Icons.Default.Label }
    }
